/* --- AES Wrapper Function --- */
static void Calculate_HLS_Reply(const unsigned char *challenge, const unsigned char *key, unsigned char *output)
{
    struct AES_ctx ctx;
    int i;

    /* Copy challenge to output buffer because tiny-AES encrypts in-place */
    for (i = 0; i < 16; i++)
    {
        output[i] = challenge[i];
    }

    /* Initialize AES context with the password as the key */
    AES_init_ctx(&ctx, key);

    /* Encrypt the challenge using AES-128 ECB */
    AES_ECB_encrypt(&ctx, output);
}

