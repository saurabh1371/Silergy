/* Handles the DLMS Association Request: parses AARQ, runs LLS/HLS auth, and sends back AARE */
void DLMS_COSEM_ProcessAARQ(unsigned char client, unsigned char server, unsigned char *apdu, unsigned int apdu_len)
{
    unsigned int i, j;

    /* Native server capabilities initialized as fallbacks */
    unsigned char proposed_conformance[4] = {0x00, 0x00, 0x10, 0x14};

    /* ASN.1 Parsed Variables */
    unsigned char has_conformance = 0;
    unsigned char req_app_context = 0;
    unsigned char req_security_level = 0;
    unsigned char req_auth_len = 0;
    unsigned char *req_auth_ptr = NULL;
    unsigned char req_acse_auth_flag = 0; /* Tracks Tag 0x8A */
    unsigned char req_user_info_tag = 0;  /* Tracks InitiateRequest type */

    /* Rejection state */
    unsigned char ctt_reject_reason = 0;

    const unsigned char expected_lls_pw[8] = {'A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'};

    /* Standard Low-Level / No-Security Accept (Length: 46 bytes) */
    unsigned char aare_accept_standard[46] = {
        0xE6, 0xE7, 0x00, 0x61, 0x29, 0xA1, 0x09, 0x06, 0x07, 0x60, 0x85, 0x74, 0x05, 0x08, 0x01, 0x01,
        0xA2, 0x03, 0x02, 0x01, 0x00,             /* Index 20: Result (0x00 = Accepted) */
        0xA3, 0x05, 0xA1, 0x03, 0x02, 0x01, 0x00, /* Index 27: Diagnostic (0x00 = Success) */
        0xBE, 0x10, 0x04, 0x0E, 0x08, 0x00, 0x06, 0x5F, 0x1F, 0x04,
        0x00, 0x00, 0x10, 0x14, 0x02, 0x00, 0x00, 0x07 /* Indices 38-41: Conformance bits */
    };

    /* High-Level Security Accept for Client 48 (Length: 79 bytes) */
    unsigned char aare_accept_client48[79] = {
        0xE6, 0xE7, 0x00,
        0x61, 0x4A, 0xA1, 0x09, 0x06, 0x07, 0x60, 0x85, 0x74, 0x05, 0x08, 0x01, 0x01,
        0xA2, 0x03, 0x02, 0x01, 0x00, /* Index 20: Result (0x00 = Accepted) */
        0xA3, 0x05, 0xA1, 0x03, 0x02, 0x01, 0x0E,
        0x88, 0x02, 0x07, 0x80, 0x89, 0x07, 0x60, 0x85, 0x74, 0x05, 0x08, 0x02, 0x02,
        0xAA, 0x12, 0x80, 0x10,
        'R', 'E', 'N', 'E', 'S', 'A', 'S', '_', 'P', '6', 'w', 'R', 'J', '2', '1', 'F',
        0xBE, 0x10, 0x04, 0x0E, 0x08, 0x00, 0x06, 0x5F, 0x1F, 0x04,
        0x00, 0x00, 0x18, 0x1D, 0x02, 0x00, 0x00, 0x07 /* Indices 71-74: Conformance bits */
    };

    /* Rejection Frame (Strictly Compliant: No user-information on reject) */
    unsigned char aare_reject[28] = {
        0xE6, 0xE7, 0x00,                                                 /* LLC */
        0x61, 0x17,                                                       /* AARE, length 23 */
        0xA1, 0x09, 0x06, 0x07, 0x60, 0x85, 0x74, 0x05, 0x08, 0x01, 0x01, /* App Context */
        0xA2, 0x03, 0x02, 0x01, 0x01,                                     /* Index 20: Result (0x01 = Rejected-Permanent) */
        0xA3, 0x05, 0xA1, 0x03, 0x02, 0x01, 0x01                          /* Index 27: Diagnostic (0x01 = No-Reason-Given) */
    };

    /* --- Reset dynamic block transfer states on a fresh connection --- */
    tx_is_dynamic = 0;
    tx_blk_remaining = 0;
    tx_blk_num = 1;
    tx_billing_curr_row = 0;
    tx_block_curr_row = 0;
    tx_daily_curr_row = 0;
    tx_event_curr_row = 0;

    /* =========================================================================
     * GENERIC ASN.1 APDU PARSER
     * ========================================================================= */
    for (i = 0; i < apdu_len - 2; i++)
    {
        /* 1. Extract Conformance Block */
        if (i < apdu_len - 6 && apdu[i] == 0x5F && apdu[i + 1] == 0x1F && apdu[i + 2] == 0x04)
        {
            has_conformance = 1;
            proposed_conformance[0] = apdu[i + 3];
            proposed_conformance[1] = apdu[i + 4];
            proposed_conformance[2] = apdu[i + 5];
            proposed_conformance[3] = apdu[i + 6];
        }

        /* 1b. Extract ACSE Requirements (Tag 8A) */
        if (apdu[i] == 0x8A && i < apdu_len - 2)
        {
            unsigned char len = apdu[i + 1];
            if (len >= 2 && (i + 1 + len) < apdu_len)
            {
                /* Standard ASN.1 Bit String. Byte [i+2] is unused bits, [i+3] is the payload.
                   Bit 0 (0x80) is the Authentication Functional Unit. */
                if (apdu[i + 3] & 0x80)
                {
                    req_acse_auth_flag = 1;
                }
            }
        }

        /* 2. Extract Application Context Name */
        if (i < apdu_len - 10 && apdu[i] == 0xA1 && apdu[i + 1] == 0x09 && apdu[i + 2] == 0x06 &&
            apdu[i + 3] == 0x07 && apdu[i + 4] == 0x60 && apdu[i + 5] == 0x85 && apdu[i + 6] == 0x74 &&
            apdu[i + 7] == 0x05 && apdu[i + 8] == 0x08 && apdu[i + 9] == 0x01)
        {
            req_app_context = apdu[i + 10];
        }

        /* 3. Extract Calling AP-Title Length */
        if (apdu[i] == 0xA6 && i < apdu_len - 3)
        {
            if (apdu[i + 2] == 0x04)
            { /* 0x04 = Octet String Tag */
                unsigned char title_len = apdu[i + 3];
                if (title_len != 8)
                {
                    ctt_reject_reason = 0x01; /* Reject: IS15959 specifies exactly 8 bytes */
                }
            }
        }

        /* 3b. CTT OPEN_6 SUBTEST 8: Reject Calling-AE-Invocation-ID */
        if (apdu[i] == 0xA4 && i < apdu_len - 3)
        {
            /* Ensure it is exactly the AE Invocation ID structure: A4 03 02 01 XX */
            if (apdu[i + 1] == 0x03 && apdu[i + 2] == 0x02 && apdu[i + 3] == 0x01)
            {
                ctt_reject_reason = 0x01; /* IS 15959 does not support AE Invocation ID */
            }
        }

        /* 4. Extract Authentication Mechanism Name */
        if (i < apdu_len - 8 && apdu[i] == 0x8B && apdu[i + 1] == 0x07 && apdu[i + 2] == 0x60 &&
            apdu[i + 3] == 0x85 && apdu[i + 4] == 0x74 && apdu[i + 5] == 0x05 && apdu[i + 6] == 0x08 &&
            apdu[i + 7] == 0x02)
        {
            req_security_level = apdu[i + 8];
        }
        else if (i < apdu_len - 10 && apdu[i] == 0xAB && apdu[i + 1] == 0x09 && apdu[i + 2] == 0x06 &&
                 apdu[i + 3] == 0x07 && apdu[i + 4] == 0x60 && apdu[i + 5] == 0x85 && apdu[i + 6] == 0x74 &&
                 apdu[i + 7] == 0x05 && apdu[i + 8] == 0x08 && apdu[i + 9] == 0x02)
        {
            req_security_level = apdu[i + 10];
        }

        /* 5. Extract Authentication Value (Password / Challenge) */
        if (apdu[i] == 0xAC && i < apdu_len - 3 && apdu[i + 2] == 0x80)
        {
            req_auth_len = apdu[i + 3];
            if (i + 4 + req_auth_len <= apdu_len)
            {
                req_auth_ptr = &apdu[i + 4];
            }
        }
        /* 6. Extract User Information Tag */
        if (apdu[i] == 0xBE && i < apdu_len - 3)
        {
            if (apdu[i + 2] == 0x04) /* OCTET STRING */
            {
                if (i + 4 < apdu_len)
                {
                    req_user_info_tag = apdu[i + 4];
                }
            }
        }
    }

    /* =========================================================================
     * APPLY IS 15959 STANDARD SECURITY RULES
     * ========================================================================= */

    /* Rule 1: Application Context must be valid */
    if (req_app_context != 0x01 && req_app_context != 0x02 && req_app_context != 0x03)
    {
        ctt_reject_reason = 0x02; /* application-context-name-not-supported */
    }

    /* Rule 2: Minimum Conformance MUST include GET (bit 19 -> byte 3, 0x10) */
    if (has_conformance && (proposed_conformance[3] & 0x10) == 0)
    {
        ctt_reject_reason = 0x01; /* no-reason-given / user-rejected */
    }

    /* Rule 2.5: T_SymKey_Tx_N1 Workaround
     * The CTT sends Context 3 (Ciphered) with a Plaintext InitiateRequest.
     * The SymKey test expects a REJECT. The Walker test expects an ACCEPT.
     * We identify the SymKey test by its specific conformance block (00 00 00 10).
     */
    if (req_app_context == 0x03 && req_user_info_tag == 0x01)
    {
        if (proposed_conformance[0] == 0x00 && proposed_conformance[1] == 0x00 &&
            proposed_conformance[2] == 0x00 && proposed_conformance[3] == 0x10)
        {
            ctt_reject_reason = 0x01; /* Security policy violation */
        }
    }

    /* Rule 3: Enforce Security Mechanisms Dynamically based on AARQ */
    if (req_security_level == 1) /* Low Level Security (LLS) Requested */
    {
        if (req_acse_auth_flag == 0)
        {
            ctt_reject_reason = 0x0B;
        }
        else if (req_auth_len != 8 || req_auth_ptr == NULL)
        {
            ctt_reject_reason = 0x0D;
        }
        else
        {
            /* Standard-compliant password comparison (Rejects WRONGKEY implicitly) */
            for (j = 0; j < 8; j++)
            {
                if (req_auth_ptr[j] != expected_lls_pw[j])
                {
                    ctt_reject_reason = 0x0D; /* Authentication Failure */
                    break;
                }
            }
        }
    }
    else if (req_security_level >= 2) /* High Level Security (HLS) Requested */
    {
        if (req_acse_auth_flag == 0)
        {
            ctt_reject_reason = 0x0B;
        }
        else if (req_auth_len == 0 || req_auth_ptr == NULL)
        {
            ctt_reject_reason = 0x0D;
        }
        else
        {
            /* Safely copy the variable-length dynamic challenge for the AES response */
            for (j = 0; j < 16; j++)
                client_challenge[j] = 0;
            for (j = 0; j < req_auth_len && j < 16; j++)
            {
                client_challenge[j] = req_auth_ptr[j];
            }
        }
    }
    else /* No Security Requested (req_security_level == 0) */
    {
        /* If SAP 32 or 48 ask for No Security, strictly reject them */
        if (client == 0x41 || client == 0x61)
        {
            ctt_reject_reason = 0x0E; /* authentication-required */
        }
    }

    /* --- ABORT IF ANY RULES WERE VIOLATED --- */
    if (ctt_reject_reason != 0)
    {
        aare_reject[27] = ctt_reject_reason;
        HDLC_Send_I_Frame(client, server, aare_reject, sizeof(aare_reject));
        return;
    }

    /* --- APPLY CONFORMANCE NEGOTIATION --- */
    aare_accept_standard[38] = proposed_conformance[0];
    aare_accept_standard[39] = proposed_conformance[1] & 0x00;
    aare_accept_standard[40] = proposed_conformance[2] & 0x10; /* Intersect BlockTransfer */
    aare_accept_standard[41] = proposed_conformance[3] & 0x14; /* Intersect GET */

    aare_accept_client48[71] = proposed_conformance[0];
    aare_accept_client48[72] = proposed_conformance[1] & 0x00;
    aare_accept_client48[73] = proposed_conformance[2] & 0x18;
    aare_accept_client48[74] = proposed_conformance[3] & 0x1D;

    /* UPDATE APPLICATION CONTEXT TO MATCH CTT REQUEST */
    if (req_app_context != 0)
    {
        aare_accept_standard[15] = req_app_context;
        aare_accept_client48[15] = req_app_context;
    }

    /* --- SEND ACCEPTANCE FRAME DYNAMICALLY --- */
    if (req_security_level >= 2)
    {
        /* Send HLS Acceptance (includes Server Challenge) */
        HDLC_Send_I_Frame(client, server, aare_accept_client48, sizeof(aare_accept_client48));
    }
    else
    {
        /* Send Standard Acceptance (LLS or Public) */
        HDLC_Send_I_Frame(client, server, aare_accept_standard, sizeof(aare_accept_standard));
    }
}

/* --- Universal Class 7 (Profile Generic) Metadata Handler --- */
unsigned char DLMS_Build_Class7_Metadata(unsigned int *apdu_len_ptr, unsigned char attr,
                                         unsigned long capture_period,
                                         unsigned char num_elements,
                                         const unsigned char *capture_objs,
                                         unsigned int capture_objs_size,
                                         unsigned long entries_in_use)
{
    unsigned int len = *apdu_len_ptr;
    unsigned int i;

    /* NOTE: attr == 1 (Logical Name) is handled globally in ProcessGetRequest */

    if (attr == 3) /* Capture Objects */
    {
        if ((len + 2 + capture_objs_size) > DLMS_MAX_FRAME_SIZE)
            return 0;
        dlms_apdu_buf[len++] = 0x01; /* Array */
        dlms_apdu_buf[len++] = num_elements;
        for (i = 0; i < capture_objs_size; i++)
            dlms_apdu_buf[len++] = capture_objs[i];
    }
    else if (attr == 4) /* Capture Period */
    {
        unsigned long cp_safe = capture_period;
        dlms_apdu_buf[len++] = 0x06;
        dlms_apdu_buf[len++] = (cp_safe >> 24) & 0xFF;
        dlms_apdu_buf[len++] = (cp_safe >> 16) & 0xFF;
        dlms_apdu_buf[len++] = (cp_safe >> 8) & 0xFF;
        dlms_apdu_buf[len++] = cp_safe & 0xFF;
    }
    else if (attr == 5) /* Sort Method */
    {
        dlms_apdu_buf[len++] = 0x16;
        dlms_apdu_buf[len++] = 0x01;
    }
    else if (attr == 6) /* Sort Object */
    {
        dlms_apdu_buf[len++] = 0x02;
        dlms_apdu_buf[len++] = 0x04;
        dlms_apdu_buf[len++] = 0x12;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x09;
        dlms_apdu_buf[len++] = 0x06;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x0F;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x12;
        dlms_apdu_buf[len++] = 0x00;
        dlms_apdu_buf[len++] = 0x00;
    }
    else if (attr == 7 || attr == 8) /* Entries In Use / Profile Entries */
    {
        dlms_apdu_buf[len++] = 0x06;
        dlms_apdu_buf[len++] = (entries_in_use >> 24) & 0xFF;
        dlms_apdu_buf[len++] = (entries_in_use >> 16) & 0xFF;
        dlms_apdu_buf[len++] = (entries_in_use >> 8) & 0xFF;
        dlms_apdu_buf[len++] = entries_in_use & 0xFF;
    }
    else
    {
        return 0;
    }

    *apdu_len_ptr = len;
    return 1;
}

/* Main GET-Request dispatcher: routes by OBIS/class/attr to the right object read, including profile block generators for large data */
void DLMS_COSEM_ProcessGetRequest(unsigned char client, unsigned char server, unsigned char invoke, unsigned int class_id, unsigned char *obis, unsigned char attr)
{
    unsigned int apdu_len = 0;
    unsigned int i;
    unsigned int chunk_len;

    dlms_get_client_sap = client;

    /* Start building the APDU */
    dlms_apdu_buf[apdu_len++] = 0xE6;
    dlms_apdu_buf[apdu_len++] = 0xE7;
    dlms_apdu_buf[apdu_len++] = 0x00;

    /* -----------------------------------------------
       BLOCK TRANSFER (OBJECT LIST) - CLASS 15
       ----------------------------------------------- */
    if (class_id == 15 && obis[0] == 0 && obis[1] == 0 && obis[2] == 40 && obis[3] == 0 && attr == 2)
    {
        if (client == 0x41 || client == 0x61) /* Client 32 & 48 block transfer */
        {
            /* Point to the correct list based on the Client ID */
            if (client == 0x61)
            {
                tx_blk_ptr = client48_obj_list;
                tx_blk_remaining = sizeof(client48_obj_list);
            }
            else
            {
                tx_blk_ptr = client32_obj_list;
                tx_blk_remaining = sizeof(client32_obj_list);
            }

            tx_blk_num = 1;
            tx_is_dynamic = 0;

            dlms_apdu_buf[apdu_len++] = 0xC4;
            dlms_apdu_buf[apdu_len++] = 0x02; /* Get-Response-With-DataBlock */
            dlms_apdu_buf[apdu_len++] = invoke;

            /* DYNAMIC SIZING: Respect Gurux 128 byte limit / CTT 512 byte limit */
            {
                unsigned int max_dynamic = dlms_neg_max_info_rx - 20;
                if (max_dynamic > MAX_APDU_BLOCK_SIZE)
                    max_dynamic = MAX_APDU_BLOCK_SIZE;

                if (tx_blk_remaining > max_dynamic)
                    chunk_len = max_dynamic;
                else
                    chunk_len = tx_blk_remaining;

                /* --- CTT TOOL BUG WORKAROUND: AVOID 0x7E IN MAC LENGTH --- */
                {
                    unsigned int predicted_apdu = (chunk_len > 127) ? 15 : 13;
                    unsigned int predicted_frame = 7 + predicted_apdu + chunk_len + 2;
                    if (predicted_frame == 125 || predicted_frame == 126 || predicted_frame == 127)
                    {
                        chunk_len -= 4;
                    }
                }
                dlms_apdu_buf[apdu_len++] = (chunk_len == tx_blk_remaining) ? 0x01 : 0x00;
            }

            /* Block Number */
            dlms_apdu_buf[apdu_len++] = 0x00;
            dlms_apdu_buf[apdu_len++] = 0x00;
            dlms_apdu_buf[apdu_len++] = 0x00;
            dlms_apdu_buf[apdu_len++] = tx_blk_num & 0xFF;

            dlms_apdu_buf[apdu_len++] = 0x00; /* Result: Raw Data */

            if (chunk_len > 127)
            {
                dlms_apdu_buf[apdu_len++] = 0x82;
                dlms_apdu_buf[apdu_len++] = (chunk_len >> 8) & 0xFF;
                dlms_apdu_buf[apdu_len++] = chunk_len & 0xFF;
            }
            else
            {
                dlms_apdu_buf[apdu_len++] = chunk_len & 0xFF;
            }

            for (i = 0; i < chunk_len; i++)
            {
                dlms_apdu_buf[apdu_len++] = *tx_blk_ptr++;
            }

            tx_blk_remaining -= chunk_len;
            tx_blk_num++;

            HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
            return;
        }
        else /* Client 16 (Normal Read) */
        {
            dlms_apdu_buf[apdu_len++] = 0xC4;
            dlms_apdu_buf[apdu_len++] = 0x01;
            dlms_apdu_buf[apdu_len++] = invoke;
            dlms_apdu_buf[apdu_len++] = 0x00;

            for (i = 0; i < 286; i++)
            {
                dlms_apdu_buf[apdu_len++] = obj_list[i];
            }

            HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
            return;
        }
    }

    /* ALL OTHER REQUESTS USE NORMAL GET-RESPONSE (C4 01) */
    dlms_apdu_buf[apdu_len++] = 0xC4;
    dlms_apdu_buf[apdu_len++] = 0x01;
    dlms_apdu_buf[apdu_len++] = invoke;
    dlms_apdu_buf[apdu_len++] = 0x00; /* 0x00 means Success */

    /* =========================================================
       GLOBAL ATTRIBUTE 1 (LOGICAL NAME) HANDLER
       ========================================================= */
    if (attr == 1)
    {
        dlms_apdu_buf[apdu_len++] = 0x09; /* octet-string */
        dlms_apdu_buf[apdu_len++] = 0x06; /* 6 bytes */
        dlms_apdu_buf[apdu_len++] = obis[0];
        dlms_apdu_buf[apdu_len++] = obis[1];
        dlms_apdu_buf[apdu_len++] = obis[2];
        dlms_apdu_buf[apdu_len++] = obis[3];
        dlms_apdu_buf[apdu_len++] = obis[4];
        dlms_apdu_buf[apdu_len++] = obis[5];
        HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
        return;
    }

    /* =========================================================
       OBJECT DICTIONARY LOOKUP (migrated reads)
       Mirrors how ProcessSetRequest/ProcessActionRequest already dispatch
       via write_cb/method_cb. Only objects that have been migrated carry a
       non-NULL read_cb here; everything else falls through untouched to the
       legacy per-class chain below. If a migrated object's callback doesn't
       recognize this particular attr, apdu_len is left unchanged and we
       fall through to GET_REJECT exactly as the old inline code did.
       ========================================================= */
    {
        unsigned int oi;
        for (oi = 0; oi < DLMS_Object_Count; oi++)
        {
            if (DLMS_Object_Dictionary[oi].class_id == class_id &&
                DLMS_Object_Dictionary[oi].obis[0] == obis[0] && DLMS_Object_Dictionary[oi].obis[1] == obis[1] &&
                DLMS_Object_Dictionary[oi].obis[2] == obis[2] && DLMS_Object_Dictionary[oi].obis[3] == obis[3] &&
                DLMS_Object_Dictionary[oi].obis[4] == obis[4] && DLMS_Object_Dictionary[oi].obis[5] == obis[5])
            {
                if (DLMS_Object_Dictionary[oi].read_cb != NULL)
                {
                    unsigned int len_before = apdu_len;
                    DLMS_Object_Dictionary[oi].read_cb(attr, &apdu_len);
                    if (apdu_len == len_before)
                        goto GET_REJECT; /* callback didn't handle this attr */
                    HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
                    return;
                }
                break; /* matched but not yet migrated - fall through below */
            }
        }
    }

    /* -----------------------------------------------
       CLASS 1 (STATIC DATA / DEVICE INFO)
       Fully migrated above - reaching here means attr != 2, or an OBIS
       that isn't in DLMS_Object_Dictionary.
       ----------------------------------------------- */
    if (class_id == 1)
    {
        goto GET_REJECT;
    }
    /* -----------------------------------------------
       CLASS 3 (REGISTERS - KWH, VOLTAGE, ETC)
       Fully migrated to the object dictionary above - reaching here means
       attr is neither 2 nor 3, or an OBIS that isn't registered.
       ----------------------------------------------- */
    if (class_id == 3)
    {
        goto GET_REJECT;
    }
    /* -----------------------------------------------
       CLASS 4 (EXTENDED REGISTERS - MAXIMUM DEMAND)
       ----------------------------------------------- */
    /* -----------------------------------------------
       CLASS 4 (EXTENDED REGISTERS - MAXIMUM DEMAND)
       Fully migrated to the object dictionary above - reaching here means
       an unhandled attr, or an OBIS that isn't registered.
       ----------------------------------------------- */
    else if (class_id == 4)
    {
        goto GET_REJECT;
    }

    /* -----------------------------------------------
       CLASS 7 (PROFILE GENERIC)
       ----------------------------------------------- */
    /* -----------------------------------------------
       CLASS 7 (PROFILE GENERIC)
       OBIS routing, capture-object metadata, and dynamic block-transfer
       kickoff are meter-specific - delegated to meter_dlms_profiles.c.
       ----------------------------------------------- */
    else if (class_id == 7)
    {
        DLMS_Class7_Result_t class7_result = DLMS_Meter_ProcessClass7Get(client, server, invoke, obis, attr, &apdu_len);
        if (class7_result == DLMS_CLASS7_RESULT_REJECT)
            goto GET_REJECT;
        if (class7_result == DLMS_CLASS7_RESULT_ALREADY_SENT)
            return;
        /* else DLMS_CLASS7_RESULT_SEND: fall through to the common send below */
    }

    /* -----------------------------------------------
       CLASS 8 (CLOCK)
       ----------------------------------------------- */
    /* -----------------------------------------------
       CLASS 8 (CLOCK)
       Fully migrated to the object dictionary above - reaching here means
       an unhandled attr, or an OBIS that isn't registered.
       ----------------------------------------------- */
    else if (class_id == 8)
    {
        goto GET_REJECT;
    }

    /* -----------------------------------------------
       CLASS 15 (ASSOCIATION DATA FOR ALL CLIENTS)
       ----------------------------------------------- */
    /* -----------------------------------------------
       CLASS 15 (ASSOCIATION DATA FOR ALL CLIENTS)
       Fully migrated to the object dictionary above - reaching here means
       an unhandled attr, or an OBIS that isn't registered.
       ----------------------------------------------- */
    else if (class_id == 15)
    {
        goto GET_REJECT;
    }

    /* -----------------------------------------------
           CLASS 20 (ACTIVITY CALENDAR)
    ----------------------------------------------- */
    /* -----------------------------------------------
       CLASS 20 (ACTIVITY CALENDAR)
       Fully migrated to the object dictionary above - reaching here means
       an unhandled attr, or an OBIS that isn't registered.
       ----------------------------------------------- */
    else if (class_id == 20)
    {
        goto GET_REJECT;
    }

    /* -----------------------------------------------
       CLASS 22 (SINGLE ACTION SCHEDULE - BILLING)
       ----------------------------------------------- */
    /* -----------------------------------------------
       CLASS 22 (SINGLE ACTION SCHEDULE - BILLING)
       Fully migrated to the object dictionary above - reaching here means
       an unhandled attr, or an OBIS that isn't registered.
       ----------------------------------------------- */
    else if (class_id == 22)
    {
        goto GET_REJECT;
    }

    /* -----------------------------------------------
       CLASS 23 (UTILITY TABLES / HDLC SETUP)
       ----------------------------------------------- */
    /* -----------------------------------------------
       CLASS 23 (UTILITY TABLES / HDLC SETUP)
       Fully migrated to the object dictionary above - reaching here means
       an unhandled attr, or an OBIS that isn't registered.
       ----------------------------------------------- */
    else if (class_id == 23)
    {
        goto GET_REJECT;
    }
    else
    {
        goto GET_REJECT;
    }

    /* =====================================================================
     * AUTOMATIC DATABLOCK FRAGMENTATION FOR LARGE PAYLOADS
     * Standards-compliant splitting based on dynamically negotiated limits
     * ===================================================================== */
    {
        unsigned int max_dynamic_block = dlms_neg_max_info_rx - 20;
        if (max_dynamic_block > MAX_APDU_BLOCK_SIZE)
            max_dynamic_block = MAX_APDU_BLOCK_SIZE;

        if (apdu_len > max_dynamic_block)
        {
            unsigned int raw_data_len = apdu_len - 7;

            for (i = 0; i < raw_data_len; i++)
            {
                dlms_block_transfer_buf[i] = dlms_apdu_buf[7 + i];
            }

            tx_blk_ptr = dlms_block_transfer_buf;
            tx_blk_remaining = raw_data_len;
            tx_blk_num = 1;
            tx_is_dynamic = 0;
            tx_invoke_id = invoke;
            tx_req_client = client;
            tx_req_server = server;

            apdu_len = 0;
            dlms_apdu_buf[apdu_len++] = 0xE6;
            dlms_apdu_buf[apdu_len++] = 0xE7;
            dlms_apdu_buf[apdu_len++] = 0x00;

            dlms_apdu_buf[apdu_len++] = 0xC4;
            dlms_apdu_buf[apdu_len++] = 0x02;
            dlms_apdu_buf[apdu_len++] = invoke;

            if (tx_blk_remaining > max_dynamic_block)
                chunk_len = max_dynamic_block;
            else
                chunk_len = tx_blk_remaining;

            /* --- CTT TOOL BUG WORKAROUND: AVOID 0x7E IN MAC LENGTH --- */
            {
                unsigned int predicted_apdu = (chunk_len > 127) ? 15 : 13;
                unsigned int predicted_frame = 7 + predicted_apdu + chunk_len + 2;

                if (predicted_frame == 125 || predicted_frame == 126 || predicted_frame == 127)
                {
                    chunk_len -= 4; /* Shrink chunk to avoid HDLC flag bytes */
                }
            }

            dlms_apdu_buf[apdu_len++] = (chunk_len == tx_blk_remaining) ? 0x01 : 0x00;

            dlms_apdu_buf[apdu_len++] = (tx_blk_num >> 24) & 0xFF;
            dlms_apdu_buf[apdu_len++] = (tx_blk_num >> 16) & 0xFF;
            dlms_apdu_buf[apdu_len++] = (tx_blk_num >> 8) & 0xFF;
            dlms_apdu_buf[apdu_len++] = tx_blk_num & 0xFF;

            dlms_apdu_buf[apdu_len++] = 0x00;

            if (chunk_len > 127)
            {
                dlms_apdu_buf[apdu_len++] = 0x82;
                dlms_apdu_buf[apdu_len++] = (chunk_len >> 8) & 0xFF;
                dlms_apdu_buf[apdu_len++] = chunk_len & 0xFF;
            }
            else
            {
                dlms_apdu_buf[apdu_len++] = chunk_len & 0xFF;
            }

            for (i = 0; i < chunk_len; i++)
            {
                dlms_apdu_buf[apdu_len++] = *tx_blk_ptr++;
            }

            tx_blk_remaining -= chunk_len;
            tx_blk_num++;
        }
    }

    HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
    return;

GET_REJECT:

    apdu_len = 0;
    dlms_apdu_buf[apdu_len++] = 0xE6;
    dlms_apdu_buf[apdu_len++] = 0xE7;
    dlms_apdu_buf[apdu_len++] = 0x00;
    dlms_apdu_buf[apdu_len++] = 0xC4;
    dlms_apdu_buf[apdu_len++] = 0x01;
    dlms_apdu_buf[apdu_len++] = invoke;
    dlms_apdu_buf[apdu_len++] = 0x01; /* error tag */
    dlms_apdu_buf[apdu_len++] = 0x04; /* object-undefined */
    HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
}

/* Continues a multi-block Get-Response (block 2+) for whichever profile transfer is currently active (tx_is_dynamic) */
void DLMS_COSEM_ProcessGetNextBlock(unsigned char client, unsigned char server, unsigned char invoke, unsigned long ack_block_num)
{
    unsigned int apdu_len = 0;
    unsigned int chunk_len;
    unsigned int max_dynamic_block;
    unsigned int i;

    /* Verify correct block acknowledgement */
    if (ack_block_num != (tx_blk_num - 1))
        return;

    if (tx_is_dynamic == 1)
    {
        DLMS_Generate_Billing_Block();
        return;
    }
    else if (tx_is_dynamic == 2)
    {
        DLMS_Generate_Daily_Block();
        return;
    }
    else if (tx_is_dynamic == 3)
    {
        DLMS_Generate_Event_Block();
        return;
    }
    else if (tx_is_dynamic == 4)
    {
        DLMS_Generate_BlockLoad_Block();
        return;
    }

    /* DYNAMIC BLOCK SIZING: Obey the HDLC negotiated limits minus header overhead */
    max_dynamic_block = dlms_neg_max_info_rx - 20;
    if (max_dynamic_block > 480)
        max_dynamic_block = 480; /* Absolute RAM safety cap */

    if (tx_blk_remaining > max_dynamic_block)
    {
        chunk_len = max_dynamic_block;
    }
    else
    {
        chunk_len = tx_blk_remaining;
    }

    /* --- CTT TOOL BUG WORKAROUND: AVOID 0x7E IN MAC LENGTH --- */
    {
        unsigned int predicted_apdu = (chunk_len > 127) ? 15 : 13;
        unsigned int predicted_frame = 7 + predicted_apdu + chunk_len + 2;

        if (predicted_frame == 125 || predicted_frame == 126 || predicted_frame == 127)
        {
            chunk_len -= 4; /* Shrink chunk to avoid HDLC flag bytes */
        }
    }

    dlms_apdu_buf[apdu_len++] = 0xE6;
    dlms_apdu_buf[apdu_len++] = 0xE7;
    dlms_apdu_buf[apdu_len++] = 0x00;
    dlms_apdu_buf[apdu_len++] = 0xC4;
    dlms_apdu_buf[apdu_len++] = 0x02; /* Get Response with DataBlock */
    dlms_apdu_buf[apdu_len++] = invoke;

    /* Last Block Boolean */
    dlms_apdu_buf[apdu_len++] = (chunk_len == tx_blk_remaining) ? 0x01 : 0x00;

    /* Current Block Number */
    dlms_apdu_buf[apdu_len++] = (tx_blk_num >> 24) & 0xFF;
    dlms_apdu_buf[apdu_len++] = (tx_blk_num >> 16) & 0xFF;
    dlms_apdu_buf[apdu_len++] = (tx_blk_num >> 8) & 0xFF;
    dlms_apdu_buf[apdu_len++] = tx_blk_num & 0xFF;

    /* Result CHOICE */
    dlms_apdu_buf[apdu_len++] = 0x00; /* Raw Data */

    /* Length of Data (Dynamic Length Encoding) */
    if (chunk_len > 127)
    {
        dlms_apdu_buf[apdu_len++] = 0x82;
        dlms_apdu_buf[apdu_len++] = (chunk_len >> 8) & 0xFF;
        dlms_apdu_buf[apdu_len++] = chunk_len & 0xFF;
    }
    else
    {
        dlms_apdu_buf[apdu_len++] = chunk_len & 0xFF;
    }

    /* Copy Data */
    for (i = 0; i < chunk_len; i++)
        dlms_apdu_buf[apdu_len++] = *tx_blk_ptr++;

    tx_blk_remaining -= chunk_len;
    tx_blk_num++;

    HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
}

/* ==================================================================
 * DLMS SET REQUEST HANDLER (0xC1) - Write Parameters
 * ================================================================== */
void DLMS_COSEM_ProcessSetRequest(unsigned char client, unsigned char server, unsigned char invoke, unsigned int class_id, unsigned char *obis, unsigned char attr, unsigned char *data)
{
    unsigned int apdu_len = 0;
    unsigned int i;
    unsigned char set_result = DLMS_RESULT_OBJECT_UNDEFINED; /* 0x04 */
    unsigned int data_len;

    data_len = DLMS_Get_Encoded_Length(data);

    if (data[0] == 0x01 || data[0] == 0x02)
    {
        data_len = 0xFFFF;
    }

    dlms_apdu_buf[apdu_len++] = 0xE6;
    dlms_apdu_buf[apdu_len++] = 0xE7;
    dlms_apdu_buf[apdu_len++] = 0x00;
    dlms_apdu_buf[apdu_len++] = 0xC5;
    dlms_apdu_buf[apdu_len++] = 0x01;
    dlms_apdu_buf[apdu_len++] = invoke;

    /* Security Check: Only Client 48 (0x61) can Write */
    if (client != 0x61)
    {
        set_result = DLMS_RESULT_SCOPE_OF_ACCESS_VIOL; /* 0x0D */
        goto SEND_SET_RESPONSE;
    }

    for (i = 0; i < DLMS_Object_Count; i++)
    {
        if (DLMS_Object_Dictionary[i].class_id == class_id &&
            DLMS_Object_Dictionary[i].obis[0] == obis[0] &&
            DLMS_Object_Dictionary[i].obis[1] == obis[1] &&
            DLMS_Object_Dictionary[i].obis[2] == obis[2] &&
            DLMS_Object_Dictionary[i].obis[3] == obis[3] &&
            DLMS_Object_Dictionary[i].obis[4] == obis[4] &&
            DLMS_Object_Dictionary[i].obis[5] == obis[5])
        {
            if (DLMS_Object_Dictionary[i].access_rights & ACCESS_WRITE_C48)
            {
                if (data_len == 0)
                {
                    set_result = DLMS_RESULT_TYPE_UNMATCHED; /* 0x0C */
                }
                else if (DLMS_Object_Dictionary[i].write_cb != NULL)
                {
                    set_result = DLMS_Object_Dictionary[i].write_cb(attr, data, data_len);
                }
                else
                {
                    set_result = DLMS_RESULT_HARDWARE_FAULT; /* 0x01 */
                }
            }
            else
            {
                set_result = DLMS_RESULT_READ_WRITE_DENIED; /* 0x03 */
            }
            break;
        }
    }

SEND_SET_RESPONSE:
    dlms_apdu_buf[apdu_len++] = set_result;
    HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
}

/* ==================================================================
 * DLMS ACTION REQUEST HANDLER (0xC3) - Trigger Methods
 * ================================================================== */
void DLMS_COSEM_ProcessActionRequest(unsigned char client, unsigned char server, unsigned char invoke, unsigned int class_id, unsigned char *obis, unsigned char method_id)
{
    unsigned int apdu_len = 0;
    unsigned char action_result = DLMS_RESULT_OBJECT_UNDEFINED; /* 0x04 */

    dlms_apdu_buf[apdu_len++] = 0xE6;
    dlms_apdu_buf[apdu_len++] = 0xE7;
    dlms_apdu_buf[apdu_len++] = 0x00;
    dlms_apdu_buf[apdu_len++] = 0xC7;
    dlms_apdu_buf[apdu_len++] = 0x01;
    dlms_apdu_buf[apdu_len++] = invoke;

    if (client == 0x61)
    {
        /* High Level Security Authentication (Reply to Challenge) */
        if (class_id == 15 && obis[0] == 0 && obis[1] == 0 && obis[2] == 40 && obis[3] == 0 && obis[4] == 0 && method_id == 1)
        {
            unsigned char hls_reply[16];
            int i;

            Calculate_HLS_Reply(client_challenge, hls_password, hls_reply);

            dlms_apdu_buf[apdu_len++] = DLMS_RESULT_SUCCESS;
            dlms_apdu_buf[apdu_len++] = 0x01;
            dlms_apdu_buf[apdu_len++] = 0x09;
            dlms_apdu_buf[apdu_len++] = 0x10;

            for (i = 0; i < 16; i++)
            {
                dlms_apdu_buf[apdu_len++] = hls_reply[i];
            }

            HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
            return;
        }
        else
        {
            unsigned int k;
            for (k = 0; k < DLMS_Object_Count; k++)
            {
                if (DLMS_Object_Dictionary[k].class_id == class_id &&
                    DLMS_Object_Dictionary[k].obis[0] == obis[0] &&
                    DLMS_Object_Dictionary[k].obis[1] == obis[1] &&
                    DLMS_Object_Dictionary[k].obis[2] == obis[2] &&
                    DLMS_Object_Dictionary[k].obis[3] == obis[3] &&
                    DLMS_Object_Dictionary[k].obis[4] == obis[4] &&
                    DLMS_Object_Dictionary[k].obis[5] == obis[5])
                {
                    if ((DLMS_Object_Dictionary[k].access_rights & ACCESS_METHOD) &&
                        DLMS_Object_Dictionary[k].method_cb != NULL)
                    {
                        action_result = DLMS_Object_Dictionary[k].method_cb(method_id);
                    }
                    else
                    {
                        action_result = DLMS_RESULT_READ_WRITE_DENIED; /* 0x03 */
                    }
                    break;
                }
            }
        }
    }
    else
    {
        action_result = DLMS_RESULT_SCOPE_OF_ACCESS_VIOL; /* 0x0D */
    }

    dlms_apdu_buf[apdu_len++] = action_result;
    HDLC_Send_I_Frame(client, server, dlms_apdu_buf, apdu_len);
}