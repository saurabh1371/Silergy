/* ==================================================================
 * DLMS PAYLOAD FORMATTING HELPERS
 * ================================================================== */
void DLMS_Inject_Type05_Uint32(unsigned int *len_ptr, unsigned long val)
{
    dlms_apdu_buf[(*len_ptr)++] = 0x05; /* Double-long-signed */
    dlms_apdu_buf[(*len_ptr)++] = (val >> 24) & 0xFF;
    dlms_apdu_buf[(*len_ptr)++] = (val >> 16) & 0xFF;
    dlms_apdu_buf[(*len_ptr)++] = (val >> 8) & 0xFF;
    dlms_apdu_buf[(*len_ptr)++] = val & 0xFF;
}

void DLMS_Inject_Type12_Uint16(unsigned int *len_ptr, unsigned int val)
{
    dlms_apdu_buf[(*len_ptr)++] = 0x12; /* Long-unsigned */
    dlms_apdu_buf[(*len_ptr)++] = (val >> 8) & 0xFF;
    dlms_apdu_buf[(*len_ptr)++] = val & 0xFF;
}

/* Returns how many bytes a DLMS-encoded value at *data occupies (type tag + length + payload) */
unsigned int DLMS_Get_Encoded_Length(unsigned char *data)
{
    switch (data[0])
    {
    case 0x00:
        return 1; /* null-data */
    case 0x03:    /* boolean */
    case 0x0F:    /* integer (int8) */
    case 0x11:    /* unsigned (uint8) */
    case 0x16:    /* enum */
        return 2;
    case 0x10: /* long (int16) */
    case 0x12: /* long-unsigned (uint16) */
        return 3;
    case 0x05: /* double-long (int32) */
    case 0x06: /* double-long-unsigned (uint32) */
    case 0x17: /* float32 */
        return 5;
    case 0x1B:
        return 5; /* time */
    case 0x1A:
        return 6; /* date */
    case 0x14:    /* long64 */
    case 0x15:    /* long64-unsigned */
    case 0x18:    /* float64 */
        return 9;
    case 0x19:
        return 13; /* date_time */
    case 0x09:     /* octet-string */
    case 0x0A:     /* visible-string */
    case 0x0C:     /* utf8-string */
        /* DYNAMIC LENGTH PARSER */
        if (data[1] < 0x80)
        {
            return 2 + data[1]; /* 0-127 bytes */
        }
        else if (data[1] == 0x81)
        {
            return 3 + data[2]; /* 128-255 bytes */
        }
        else if (data[1] == 0x82)
        {
            return 4 + ((data[2] << 8) | data[3]); /* 256-65535 bytes */
        }
        return 0;
    default:
        return 0; /* Unknown type */
    }
}

/* Encodes a real DLMS date-time octet string from the given fields */
void DLMS_Inject_DateTime(unsigned int *len_ptr, unsigned int yr, unsigned char mo, unsigned char dy, unsigned char hr, unsigned char mn, unsigned char sec)
{
    dlms_apdu_buf[(*len_ptr)++] = 0x09; /* Octet-string */
    dlms_apdu_buf[(*len_ptr)++] = 0x0C; /* 12 bytes */
    dlms_apdu_buf[(*len_ptr)++] = (yr >> 8) & 0xFF;
    dlms_apdu_buf[(*len_ptr)++] = yr & 0xFF;
    dlms_apdu_buf[(*len_ptr)++] = (mo == 0 || mo > 12) ? 1 : mo;
    dlms_apdu_buf[(*len_ptr)++] = (dy == 0 || dy > 31) ? 1 : dy;
    dlms_apdu_buf[(*len_ptr)++] = 0xFF; /* Day of week (0xFF = unspecified) */
    dlms_apdu_buf[(*len_ptr)++] = (hr > 23) ? 0 : hr;
    dlms_apdu_buf[(*len_ptr)++] = (mn > 59) ? 0 : mn;
    dlms_apdu_buf[(*len_ptr)++] = (sec > 59) ? 0 : sec;
    dlms_apdu_buf[(*len_ptr)++] = 0xFF; /* Hundredths */
    dlms_apdu_buf[(*len_ptr)++] = 0x80; /* Dev High */
    dlms_apdu_buf[(*len_ptr)++] = 0x00; /* Dev Low */
    dlms_apdu_buf[(*len_ptr)++] = 0x00; /* Status */
}

/* Encodes a placeholder "not specified" DLMS date-time (0xFF fields) */
void DLMS_Inject_Dummy_DateTime(unsigned int *len_ptr)
{
    unsigned int apdu_len = *len_ptr;

    /* =========================================================================
     * STANDARD COMPLIANT NULL TIMESTAMP (IS15959 / DLMS COSEM Specification)
     * ========================================================================= */
    dlms_apdu_buf[apdu_len++] = 0x09; /* Octet-string */
    dlms_apdu_buf[apdu_len++] = 0x0C; /* 12 bytes length */

    dlms_apdu_buf[apdu_len++] = 0xFF; /* Year High (0x255 = Unspecified) */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Year Low */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Month */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Day of Month */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Day of Week */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Hour */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Minute */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Second */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Hundredths of Second */

    dlms_apdu_buf[apdu_len++] = 0x80; /* Deviation High (0x8000 = Unspecified) */
    dlms_apdu_buf[apdu_len++] = 0x00; /* Deviation Low */
    dlms_apdu_buf[apdu_len++] = 0xFF; /* Clock Status (0xFF = Not Specified) */

    *len_ptr = apdu_len;
}

